"""EXACT's per-child mutation procedure (Desell, 2017, section III-B)."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.random import Generator

from polyneat.algorithms.exact.exact_genome import EXACTGenome
from polyneat.core.component_protocols import InnovationTracker, MutationOperator


@dataclass
class EXACTCompositeMutation:
    """Applies a fixed number of operator draws, discarding unreachable children.

    Per the paper: "a user specified number of the following mutations are
    performed", each operator "selected with a user specified rate", and a
    child whose mutations left any output node unreachable "is discarded and
    a new child is generated by another attempt at mutation" (section III-B).
    After ``maximum_attempts_for_reachable_child`` failed attempts the parent
    genome is returned unchanged (the parent is always reachable: initial
    genomes are, and both crossover and this operator only emit reachable
    genomes).

    Attributes:
        mutation_operators: The seven EXACT operators, order-aligned with
            ``operator_selection_probabilities``.
        operator_selection_probabilities: Categorical distribution over the
            operators; validated to sum to 1 by ``EXACTConfig``.
        number_of_mutations_per_genome: Operator draws per child.
        maximum_attempts_for_reachable_child: Retry budget for the
            reachability discard rule.
    """

    mutation_operators: list[MutationOperator[EXACTGenome]]
    operator_selection_probabilities: list[float]
    number_of_mutations_per_genome: int
    maximum_attempts_for_reachable_child: int

    def apply_to_genome(
        self,
        genome: EXACTGenome,
        rng: Generator,
        innovation_tracker: InnovationTracker,
    ) -> EXACTGenome:
        """Return a mutated child with all outputs reachable, or ``genome`` on give-up.

        Args:
            genome: Parent genome.
            rng: Source of randomness for operator draws and the operators.
            innovation_tracker: Passed through to the structural operators.

        Returns:
            The child genome, or the parent unchanged when every attempt
            produced an unreachable output node.
        """
        selection_probabilities = np.asarray(self.operator_selection_probabilities)
        for _attempt in range(self.maximum_attempts_for_reachable_child):
            candidate_genome = genome
            for _draw in range(self.number_of_mutations_per_genome):
                operator_index = int(
                    rng.choice(len(self.mutation_operators), p=selection_probabilities)
                )
                candidate_genome = self.mutation_operators[operator_index].apply_to_genome(
                    genome=candidate_genome,
                    rng=rng,
                    innovation_tracker=innovation_tracker,
                )
            if candidate_genome.are_all_output_nodes_reachable():
                return candidate_genome
        return genome
